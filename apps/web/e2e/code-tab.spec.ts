/**
 * The Code tab (issue #102): beside Problems, the Java `zenith codegen` would write for the open
 * auto, updated as the auto changes, with Copy, the selected step's lines highlighted, and a click
 * on a step's code selecting the step. A project that names no command library gets one line that
 * points to Settings instead, because Zenith never picks one for a team. A project with no `codegen`
 * section is shown the exact JSON to add (issue #156). A switch shows the exported OpMode instead, with a
 * line that says it is not recommended (issues #534, #535).
 */
import { createHash } from "node:crypto";
import { expect, test, type Page } from "@playwright/test";
import {
  canonicalize,
  generateAutoJava,
  loadAuto,
  loadField,
  loadLink,
  loadRobot,
  loadWaypoints,
  plan,
  resolve,
} from "@horizon36596/zenith-core";
import { serveFolder, starterFiles } from "./opfsProject";

test.beforeEach(async ({ page, context }) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.addInitScript(() => {
    if (window.localStorage.getItem("zenith.ui") === null) {
      window.localStorage.setItem("zenith.ui", JSON.stringify({ tour: { seen: true, coreDone: true, fullDone: false } }));
    }
  });
});

async function openCodeTab(page: Page): Promise<void> {
  await page.getByTestId("bottom-tab-code").click();
  await expect(page.getByTestId("bottom-tab-code")).toHaveAttribute("aria-selected", "true");
  await expect(page.getByTestId("code-panel")).toBeVisible();
}

/**
 * What `zenith codegen` writes for the starter's first-auto, worked out here as the CLI does it, or with
 * `exported` what `zenith codegen --export` writes.
 */
function cliJavaForFirstAuto(exported = false): string {
  const files = starterFiles();
  const read = (path: string): unknown => JSON.parse(files[path] ?? "");
  const link = loadLink(read("zenith.json"));
  const robot = loadRobot(read("autos/robot.json"));
  const field = loadField(read("autos/field/biobuzz.field.json"));
  const auto = loadAuto(read("autos/first-auto.auto.json"));
  const planned = plan(resolve(auto, loadWaypoints(read("autos/waypoints.json")), robot), robot, field);
  return generateAutoJava(planned, {
    packageName: link.codegen?.package ?? "",
    shaHex: createHash("sha256").update(canonicalize("auto", auto), "utf8").digest("hex").slice(0, 8),
    sourcePath: "autos/first-auto.auto.json",
    commandLibrary: "solverslib",
    ...(exported ? { exported: { robotClass: link.deploy?.robotClass ?? "" } } : {}),
  });
}

test("the Code tab shows the example's Java, follows the selected step and updates after an edit", async ({ page }) => {
  await page.goto("/?cloud=fake");
  await page.getByTestId("canvas-load-example").click();
  await expect(page.getByTestId("step-row-driveOut")).toBeVisible();
  await openCodeTab(page);

  await expect(page.getByTestId("code-file")).toHaveText("CollectAndScoreGenerated.java");
  await expect(page.getByTestId("code-library")).toHaveText("SolversLib");
  const view = page.getByTestId("code-view");
  await expect(view).toContainText("public abstract class CollectAndScoreGenerated extends AutoFromFile {");
  await expect(view.getByTestId("code-line").first()).toContainText("1/** GENERATED by zenith from autos/collect-and-score.auto.json");

  // Selecting a step highlights the lines it wrote, and only those.
  await page.getByTestId("step-row-driveOut").getByRole("button").first().click();
  const selected = view.locator('[data-selected="true"]');
  await expect(selected.first()).toBeVisible();
  expect(await selected.count()).toBeGreaterThan(3);
  expect(new Set(await selected.evaluateAll((lines) => lines.map((line) => line.getAttribute("data-step"))))).toEqual(
    new Set(["driveOut"]),
  );
  await expect(selected.filter({ hasText: "private Command stepDriveOut()" })).toHaveCount(1);

  // An edit shows in the code at once: driveOut's speed is written into its followPath call.
  await expect(selected.filter({ hasText: "followPath(path, 0.6)" })).toHaveCount(0);
  const speed = page.getByTestId("inspector-speed");
  await speed.fill("60");
  await page.keyboard.press("Tab");
  await expect(selected.filter({ hasText: "followPath(path, 0.6)" })).toHaveCount(1);

  // Clicking another step's code selects that step.
  await view.locator('[data-step="sweepGarden"]').filter({ hasText: "private Command stepSweepGarden()" }).click();
  await expect(page.getByTestId("inspector-panel")).toContainText("sweepGarden");
  await expect(view.locator('[data-selected="true"][data-step="sweepGarden"]').first()).toBeVisible();
  await expect(view.locator('[data-selected="true"][data-step="driveOut"]')).toHaveCount(0);

  // The Problems tab is one click back.
  await page.getByTestId("bottom-tab-problems").click();
  await expect(page.getByTestId("findings-list")).toBeVisible();
  await expect(page.getByTestId("code-panel")).toHaveCount(0);
});

test("Copy puts exactly what zenith codegen writes on the clipboard", async ({ page }) => {
  await serveFolder(page, starterFiles());
  await page.goto("/?cloud=fake");
  await page.getByTestId("canvas-open-project").click();
  await expect(page.getByTestId("toolbar-auto-name")).toContainText("first-auto.auto.json");
  await openCodeTab(page);
  await expect(page.getByTestId("code-file")).toHaveText("FirstAutoGenerated.java");

  await page.getByTestId("code-copy").click();
  await expect(page.getByTestId("code-copy")).toHaveText("Copied");
  // Windows' clipboard hands text back with CRLF line ends whatever was written.
  const copied = (await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, "\n");
  expect(copied).toBe(cliJavaForFirstAuto());
  // The line numbers are for reading, not part of the code.
  expect(copied.startsWith("/** GENERATED")).toBe(true);
});

test("a project with no command library says so in one line and points to Settings", async ({ page }) => {
  await serveFolder(
    page,
    starterFiles({ "zenith.json": (text) => text.replace(/\n\s*"commandLibrary": "solverslib",/, "") }),
  );
  await page.goto("/?cloud=fake");
  await page.getByTestId("canvas-open-project").click();
  await expect(page.getByTestId("toolbar-auto-name")).toContainText("first-auto.auto.json");
  await openCodeTab(page);

  await expect(page.getByTestId("code-blocked")).toContainText(
    "Choose a command library in Settings, Robot to see the code for this auto.",
  );
  await expect(page.getByTestId("code-view")).toHaveCount(0);
  await expect(page.getByTestId("code-copy")).toHaveCount(0);
  await page.getByTestId("code-open-settings").click();
  await expect(page.getByTestId("settings")).toBeVisible();
  // It lands on Robot, under Follower, where the command library shows whether or not Commands is on.
  await expect(page.getByTestId("settings-command-library-choice")).toBeVisible();
});

test("a project with no codegen section is shown the exact JSON to add (issue #156)", async ({ page }) => {
  await serveFolder(
    page,
    starterFiles({
      "zenith.json": (text) => {
        const link = JSON.parse(text) as Record<string, unknown>;
        delete link["codegen"];
        return `${JSON.stringify(link, null, 2)}\n`;
      },
    }),
  );
  await page.goto("/?cloud=fake");
  await page.getByTestId("canvas-open-project").click();
  await expect(page.getByTestId("toolbar-auto-name")).toContainText("first-auto.auto.json");
  await openCodeTab(page);

  await expect(page.getByTestId("code-blocked")).toContainText('zenith.json has no "codegen" section');
  const json = page.getByTestId("code-blocked-json");
  await expect(json).toBeVisible();
  const shown = (await json.textContent()) ?? "";
  expect(shown).toBe(
    ['"codegen": {', '  "package": "org.firstinspires.ftc.teamcode.zenith",', '  "dir": "TeamCode/src/main/java"', "}"].join("\n"),
  );
  // It is a key and its value, which parse once wrapped in braces, as they would sit in zenith.json.
  expect(JSON.parse(`{${shown}}`)).toEqual({
    codegen: { package: "org.firstinspires.ftc.teamcode.zenith", dir: "TeamCode/src/main/java" },
  });
  await expect(page.getByTestId("code-view")).toHaveCount(0);
  await expect(page.getByTestId("code-open-settings")).toHaveCount(0);
});

test("an auto with errors says there is no code in one line and shows the errors on a click (0.1.2 UX review)", async ({ page }) => {
  await page.goto("/?cloud=fake");
  await page.getByTestId("canvas-load-example").click();
  await expect(page.getByTestId("step-row-driveOut")).toBeVisible();
  // driveOut ends on the hive frame's west base bar, which stands on the floor: an error.
  await page.evaluate(`import("/src/state/store.ts").then((m) => {
    const s = m.getState();
    const steps = s.auto.steps.map((step) => step.id !== "driveOut" ? step : {
      ...step,
      segments: step.segments.map((segment, index) => index !== step.segments.length - 1 ? segment : { ...segment, to: { xIn: -23.65, yIn: 0, provenance: "SET FROM EDITOR" } }),
    });
    m.commit({ ...s.auto, steps });
  })`);
  await openCodeTab(page);
  await expect(page.getByTestId("code-blocked")).toContainText(/^No code while the auto has \d+ errors?\./);
  await expect(page.getByTestId("code-blocked")).not.toContainText("zenith codegen");
  await page.getByTestId("code-show-errors").click();
  await expect(page.getByTestId("bottom-tab-problems")).toHaveAttribute("aria-selected", "true");
});

test("Export shows the OpMode a team owns, says it is not recommended, and Copy copies it (issue #535)", async ({ page }) => {
  await serveFolder(page, starterFiles());
  await page.goto("/?cloud=fake");
  await page.getByTestId("canvas-open-project").click();
  await expect(page.getByTestId("toolbar-auto-name")).toContainText("first-auto.auto.json");
  await openCodeTab(page);

  // The reference class says the robot does not run it (issue #534).
  await expect(page.getByTestId("code-form-reference")).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByTestId("code-note")).toContainText("The robot does not run this class.");

  await page.getByTestId("code-form-export").click();
  await expect(page.getByTestId("code-form-export")).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByTestId("code-file")).toHaveText("FirstAutoExported.java");
  await expect(page.getByTestId("code-note")).toContainText("Not recommended.");
  await expect(page.getByTestId("code-view")).toContainText("public class FirstAutoExported extends AutoFromFile {");

  await page.getByTestId("code-copy").click();
  await expect(page.getByTestId("code-copy")).toHaveText("Copied");
  const copied = (await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, "\n");
  expect(copied).toBe(cliJavaForFirstAuto(true));

  // Back to the reference, which is still what the CLI writes without --export.
  await page.getByTestId("code-form-reference").click();
  await expect(page.getByTestId("code-file")).toHaveText("FirstAutoGenerated.java");
});
