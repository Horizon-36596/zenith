/**
 * What the Code tab shows for the open auto (issue #102), as pure logic: the Java `zenith codegen`
 * would write for it, or the one line that says why there is none.
 *
 * It runs core's own generator (`generateAutoJavaWithMap`), the function the CLI writes files
 * with, so the text is the CLI's byte for byte, and it refuses in the CLI's order and, where the
 * CLI has a sentence for it, in the CLI's words: errors in the auto, then no `codegen` section in
 * `zenith.json`, then no command library. The errors' line is the editor's own, "No code while the
 * auto has 4 errors.", with a way to the errors, since the person reads it in the editor, not a
 * terminal (0.1.2 UX review). Nothing in the editor writes a `codegen` section, so that
 * refusal gives the exact JSON to add (issue #156). Neither library is a default (owner ruling), so
 * the last one points to Settings rather than picking one.
 *
 * It has two forms (issues #534 and #535). The reference class, the default, is what `zenith codegen`
 * writes: the robot does not run it, it runs the auto file, and the tab says so. The exported OpMode is
 * what `zenith codegen --export` writes: a class a team pastes in and owns, which reads no file. It is
 * not recommended, and the tab says that too.
 */
import {
  canonicalize,
  exportedClassName,
  generateAutoJavaWithMap,
  generatedClassName,
  LIBRARY_LABEL,
  NO_ROBOT_CLASS_EXPORT_MESSAGE,
  sha256Hex,
  STARTER_CODEGEN_SECTION,
  type CodegenForm,
  type CommandLibrary,
  type Finding,
  type JavaStepLines,
  type Plan,
} from "@horizon36596/zenith-core";
import type { Auto, Link } from "@horizon36596/zenith-schema";

export type CodeView =
  | {
      kind: "code";
      /** Which class this is: the reference the robot does not run, or the exported OpMode. */
      form: CodegenForm;
      /** The class file's name, e.g. `FirstAutoGenerated.java` or `FirstAutoExported.java`. */
      fileName: string;
      library: CommandLibrary;
      /** The library as a person reads it, e.g. `SolversLib`. */
      libraryLabel: string;
      text: string;
      stepLines: JavaStepLines[];
    }
  | {
      kind: "blocked";
      /** Why there is no code, in one line. */
      message: string;
      /** Set when the fix is a choice in Settings, so the tab can offer to open it. */
      settings: boolean;
      /** Set when the fix is JSON to add to `zenith.json`: exactly that JSON, shown under the line. */
      json?: string;
      /** Set when the auto's errors block the code and Problems lists any, so the tab can offer to show them. */
      errors?: boolean;
      /**
       * Set instead of `errors` when every error is in a feature the settings hide, so Problems lists
       * none of them: the tab offers to turn those features on.
       */
      hiddenErrors?: boolean;
    };

/**
 * The line the tab shows while the auto has errors: "No code while the auto has 4 errors.", with how
 * many of them sit in features the person's settings hide, since the Problems header does not count
 * those.
 */
export function errorsBlockedLine(errorCount: number, hiddenCount = 0): string {
  const errors = `${String(errorCount)} ${errorCount === 1 ? "error" : "errors"}`;
  if (hiddenCount <= 0) return `No code while the auto has ${errors}.`;
  const hidden = hiddenCount === errorCount ? (errorCount === 1 ? "it is" : "all of them are") : `${String(hiddenCount)} of them ${hiddenCount === 1 ? "is" : "are"}`;
  return `No code while the auto has ${errors}. ${hidden.charAt(0).toUpperCase()}${hidden.slice(1)} in features your settings hide.`;
}

/** The line beside the reference class (issue #534): what the robot runs, so nobody takes this class for it. */
export const REFERENCE_NOTE =
  "The robot does not run this class. It runs the auto file, which builds this same routine. Edit the auto, not the code.";

/** The line beside the exported OpMode (issue #535): what it is, and why it is not the recommended path. */
export const EXPORT_NOTE =
  "Not recommended. An OpMode you own, which runs without the auto file. Zenith no longer tracks it or sees your changes.";

/** The line the tab shows when `zenith.json` names no command library. */
export const NO_LIBRARY_LINE = "Choose a command library in Settings, Robot to see the code for this auto.";

/**
 * The line the tab shows when `zenith.json` has no `codegen` section (issue #156). Nothing in the
 * editor writes one, so the line is followed by the exact JSON to add, `CODEGEN_SECTION_JSON`.
 */
export const NO_CODEGEN_LINE =
  'zenith.json has no "codegen" section, which says which Java package and folder the code goes in. ' +
  "To see the code for this auto, add the section zenith init writes to the top level of zenith.json:";

/** The `codegen` key and value to add, as they sit in `zenith.json`: the section `zenith init` writes. */
export const CODEGEN_SECTION_JSON = `"codegen": ${JSON.stringify(
  { package: STARTER_CODEGEN_SECTION.package, dir: STARTER_CODEGEN_SECTION.dir },
  null,
  2,
)}`;

/** The line the tab shows when the auto does not plan, so there is nothing to generate from. */
export const NO_PLAN_LINE = "Zenith cannot plan this auto yet, so there is no code to show.";

/** `autos` and `first-auto.auto.json` as the CLI prints the source path: relative to the project, with slashes. */
export function sourcePathOf(autosDir: string, fileName: string): string {
  const dir = autosDir
    .split(/[\\/]+/)
    .filter((part) => part.length > 0 && part !== ".")
    .join("/");
  return dir.length === 0 ? fileName : `${dir}/${fileName}`;
}

/** The header's sha: the first 8 hex digits of SHA-256 over the auto's canonical text, as the CLI computes it. */
export const shaOf = (auto: Auto): string => sha256Hex(canonicalize("auto", auto)).slice(0, 8);

export interface CodeViewInput {
  link: Link;
  /** The open auto's file name inside `link.autosDir`, or null for an auto not saved yet. */
  fileName: string | null;
  auto: Auto;
  plan: Plan | null;
  findings: readonly Finding[];
  /** How many of the errors are in features the person's settings hide. */
  hiddenErrors?: number;
  /** Which class to show. The reference class when left out. */
  form?: CodegenForm;
}

export function codeViewOf({ link, fileName, auto, plan, findings, hiddenErrors = 0, form = "reference" }: CodeViewInput): CodeView {
  if (plan === null) return { kind: "blocked", message: NO_PLAN_LINE, settings: false };
  const errors = findings.filter((finding) => finding.severity === "error").length;
  if (errors > 0) {
    const hidden = Math.min(hiddenErrors, errors);
    const message = errorsBlockedLine(errors, hidden);
    return hidden === errors ? { kind: "blocked", message, settings: false, hiddenErrors: true } : { kind: "blocked", message, settings: false, errors: true };
  }
  const codegen = link.codegen;
  if (codegen === undefined) {
    return { kind: "blocked", message: NO_CODEGEN_LINE, settings: false, json: CODEGEN_SECTION_JSON };
  }
  const library = link.deploy?.commandLibrary;
  if (library === undefined) return { kind: "blocked", message: NO_LIBRARY_LINE, settings: true };
  const robotClass = link.deploy?.robotClass;
  // The exported OpMode constructs the robot, and Zenith never invents a class name, as the CLI refuses.
  if (form === "export" && robotClass === undefined) {
    return { kind: "blocked", message: NO_ROBOT_CLASS_EXPORT_MESSAGE, settings: false };
  }
  const preselectTeleOp = link.deploy?.preselectTeleOp;
  const generated = generateAutoJavaWithMap(plan, {
    packageName: codegen.package,
    shaHex: shaOf(auto),
    sourcePath: sourcePathOf(link.autosDir, fileName ?? `${auto.name}.auto.json`),
    commandLibrary: library,
    ...(form === "export" && robotClass !== undefined
      ? { exported: { robotClass, ...(preselectTeleOp === undefined ? {} : { preselectTeleOp }) } }
      : {}),
  });
  return {
    kind: "code",
    form,
    fileName: `${form === "export" ? exportedClassName(plan.auto.name) : generatedClassName(plan.auto.name)}.java`,
    library,
    libraryLabel: LIBRARY_LABEL[library],
    text: generated.text,
    stepLines: generated.stepLines,
  };
}

/** The id of the step that wrote 1-based `line`, or null for a line no step wrote. */
export function stepAtLine(stepLines: readonly JavaStepLines[], line: number): string | null {
  return stepLines.find((range) => range.startLine <= line && line <= range.endLine)?.stepId ?? null;
}

/**
 * The 1-based line that declares `buildRoutine()`, where the tab starts when no step is selected
 * (issue #413): the routine reads from there, past the licence and the imports. Null when the text
 * has no such line.
 */
export function routineLine(text: string): number | null {
  const at = text.split("\n").findIndex((line) => /\bbuildRoutine\(\)\s*\{/.test(line));
  return at < 0 ? null : at + 1;
}

/** Every 1-based line `stepId` wrote, for the highlight. */
export function linesOfStep(stepLines: readonly JavaStepLines[], stepId: string | undefined): Set<number> {
  const lines = new Set<number>();
  if (stepId === undefined) return lines;
  for (const range of stepLines) {
    if (range.stepId !== stepId) continue;
    for (let line = range.startLine; line <= range.endLine; line += 1) lines.add(line);
  }
  return lines;
}
