import { describe, expect, it } from "vitest";
import { tokenizeJava, type JavaToken } from "./javaTokens";

const kinds = (line: JavaToken[] | undefined): string[] =>
  (line ?? []).filter((token) => token.kind !== "plain").map((token) => `${token.kind}:${token.text}`);

describe("tokenizeJava", () => {
  it("gives one line per line of text, and the text back unchanged", () => {
    const text = "package a.b;\n\npublic class X {\n}\n";
    const lines = tokenizeJava(text);
    expect(lines).toHaveLength(5);
    expect(lines.map((line) => line.map((token) => token.text).join("")).join("\n")).toBe(text);
  });

  it("colours keywords, annotations, strings and numbers, and leaves names plain", () => {
    const [line] = tokenizeJava('    @Override protected Command x() { return step("drive", Paths.line(1.5, -2.0e3)); }');
    expect(kinds(line)).toEqual([
      "keyword:@Override",
      "keyword:protected",
      "keyword:return",
      'string:"drive"',
      "number:1.5",
      "number:2.0e3",
    ]);
  });

  it("does not colour a number inside a name", () => {
    expect(kinds(tokenizeJava("Path seg0 = seg12;")[0])).toEqual([]);
  });

  it("keeps a block comment across lines, and a line comment to the end of its line", () => {
    const lines = tokenizeJava("/**\n * GENERATED by zenith.\n */\nint a = 1; // one \"quoted\"");
    expect(kinds(lines[0])).toEqual(["comment:/**"]);
    expect(kinds(lines[1])).toEqual(["comment: * GENERATED by zenith."]);
    expect(kinds(lines[2])).toEqual(["comment: */"]);
    expect(kinds(lines[3])).toEqual(["keyword:int", "number:1", 'comment:// one "quoted"']);
  });

  it("keeps an escaped quote inside its string", () => {
    expect(kinds(tokenizeJava('x("a \\"b\\" c", 2)')[0])).toEqual(['string:"a \\"b\\" c"', "number:2"]);
  });

  it("merges plain text so a line is a few tokens, not one per character", () => {
    const [line] = tokenizeJava("a.b(c, d);");
    expect(line).toEqual([{ kind: "plain", text: "a.b(c, d);" }]);
  });
});
