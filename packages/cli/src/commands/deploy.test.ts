import { cpSync, existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { makeProject, simpleAuto, writeAuto } from "../testSupport.js";
import { main } from "../index.js";
import { runDeploy } from "./deploy.js";

let root = "";
let out: string[] = [];

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "zenith-deploy-"));
  out = [];
  vi.spyOn(process.stdout, "write").mockImplementation((chunk: unknown) => {
    out.push(String(chunk));
    return true;
  });
});

afterEach(() => {
  vi.restoreAllMocks();
  rmSync(root, { recursive: true, force: true });
});

describe("zenith deploy", () => {
  it("copies the auto, waypoints, robot and field files into deploy.dir and writes a stub", () => {
    makeProject(root);
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    const code = runDeploy({ cwd: root });
    expect(code).toBe(0);
    expect(existsSync(join(root, "deploy/demo.auto.json"))).toBe(true);
    expect(existsSync(join(root, "deploy/waypoints.json"))).toBe(true);
    expect(existsSync(join(root, "deploy/robot.json"))).toBe(true);
    expect(existsSync(join(root, "deploy/field.json"))).toBe(true);
    const stub = join(root, "java/org/example/teamcode/opmode/Auto/generated/DemoAuto.java");
    expect(existsSync(stub)).toBe(true);
    const text = readFileSync(stub, "utf8");
    expect(text).toContain("extends AutoFromFile");
    expect(text).toContain('return "demo";');
    expect(text).toContain("@Autonomous(");
  });

  it("skips an auto whose file name does not match its name, since the robot loads it by name", () => {
    makeProject(root);
    // Renamed in Explorer from old.auto.json, "name" left as "old".
    writeAuto(root, "autos", "new", simpleAuto("old"));
    const code = runDeploy({ cwd: root });
    expect(code).not.toBe(0);
    expect(out.join("")).toContain('name "old" does not match the file name new.auto.json');
    expect(existsSync(join(root, "deploy/new.auto.json"))).toBe(false);
    expect(existsSync(join(root, "java/org/example/teamcode/opmode/Auto/generated/OldAuto.java"))).toBe(false);
  });

  it("gives a skipped auto's name, so a reader can name the OpMode it no longer writes", () => {
    makeProject(root);
    writeAuto(root, "autos", "new", simpleAuto("old"));
    runDeploy({ cwd: root, json: true, dryRun: true });
    const report = JSON.parse(out.join("")) as { actions: { kind: string; path: string; autoName?: string }[] };
    expect(report.actions.find((action) => action.kind === "skip")).toMatchObject({ path: "autos/new.auto.json", autoName: "old" });
  });

  it("writes a stub that extends the published runtime's AutoFromFile and constructs deploy.robotClass", () => {
    makeProject(root);
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(runDeploy({ cwd: root })).toBe(0);
    const stub = readFileSync(join(root, "java/org/example/teamcode/opmode/Auto/generated/DemoAuto.java"), "utf8");
    expect(stub).toBe(
      [
        "package org.example.teamcode.opmode.Auto.generated;",
        "",
        "import com.qualcomm.robotcore.eventloop.opmode.Autonomous;",
        "import org.horizon36596.zenith.solverslib.AutoFromFile;",
        "import org.horizon36596.zenith.solverslib.ZenithRobot;",
        "",
        "/** GENERATED by zenith deploy from autos/demo.auto.json. Do not edit; edit the file and re-run zenith deploy. */",
        '@Autonomous(name = "demo", group = "Generated")',
        "public final class DemoAuto extends AutoFromFile {",
        '    @Override protected String autoName() { return "demo"; }',
        "    @Override protected ZenithRobot createRobot() { return new org.example.teamcode.zenith.ExampleRobot(); }",
        "}",
        "",
      ].join("\n"),
    );
  });

  it("preselects the TeleOp named in deploy.preselectTeleOp, and only then", () => {
    makeProject(root, {
      deploy: {
        kind: "directory",
        dir: "deploy",
        commandLibrary: "solverslib",
        robotClass: "org.example.teamcode.zenith.ExampleRobot",
        preselectTeleOp: "Driver Control",
      },
    });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(runDeploy({ cwd: root })).toBe(0);
    const stub = readFileSync(join(root, "java/org/example/teamcode/opmode/Auto/generated/DemoAuto.java"), "utf8");
    expect(stub).toContain('@Autonomous(name = "demo", group = "Generated", preselectTeleOp = "Driver Control")');
  });

  it("extends the team's own base class when deploy.opModeBase names one (issue #533)", () => {
    makeProject(root, {
      deploy: {
        kind: "directory",
        dir: "deploy",
        commandLibrary: "ivy",
        robotClass: "org.example.teamcode.zenith.ExampleRobot",
        opModeBase: "org.example.teamcode.zenith.LoggedAuto",
      },
    });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(runDeploy({ cwd: root })).toBe(0);
    const stub = readFileSync(join(root, "java/org/example/teamcode/opmode/Auto/generated/DemoAuto.java"), "utf8");
    expect(stub).toBe(
      [
        "package org.example.teamcode.opmode.Auto.generated;",
        "",
        "import com.qualcomm.robotcore.eventloop.opmode.Autonomous;",
        "import org.horizon36596.zenith.ivy.ZenithRobot;",
        "",
        "/** GENERATED by zenith deploy from autos/demo.auto.json. Do not edit; edit the file and re-run zenith deploy. */",
        '@Autonomous(name = "demo", group = "Generated")',
        "public final class DemoAuto extends org.example.teamcode.zenith.LoggedAuto {",
        '    @Override protected String autoName() { return "demo"; }',
        "    @Override protected ZenithRobot createRobot() { return new org.example.teamcode.zenith.ExampleRobot(); }",
        "}",
        "",
      ].join("\n"),
    );
  });

  it("refuses an opModeBase that is not a Java class name, since it is written into Java source", () => {
    makeProject(root, {
      deploy: {
        kind: "directory",
        dir: "deploy",
        commandLibrary: "solverslib",
        robotClass: "org.example.teamcode.zenith.ExampleRobot",
        opModeBase: "LoggedAuto { }; class X",
      },
    });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(() => runDeploy({ cwd: root })).toThrow(/opModeBase|fully qualified Java class name/);
  });

  it('writes stubs for the Ivy runtime when deploy.commandLibrary is "ivy"', () => {
    makeProject(root, {
      deploy: {
        kind: "directory",
        dir: "deploy",
        commandLibrary: "ivy",
        robotClass: "org.example.teamcode.zenith.ExampleRobot",
      },
    });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(runDeploy({ cwd: root })).toBe(0);
    const stub = readFileSync(join(root, "java/org/example/teamcode/opmode/Auto/generated/DemoAuto.java"), "utf8");
    expect(stub).toBe(
      [
        "package org.example.teamcode.opmode.Auto.generated;",
        "",
        "import com.qualcomm.robotcore.eventloop.opmode.Autonomous;",
        "import org.horizon36596.zenith.ivy.AutoFromFile;",
        "import org.horizon36596.zenith.ivy.ZenithRobot;",
        "",
        "/** GENERATED by zenith deploy from autos/demo.auto.json. Do not edit; edit the file and re-run zenith deploy. */",
        '@Autonomous(name = "demo", group = "Generated")',
        "public final class DemoAuto extends AutoFromFile {",
        '    @Override protected String autoName() { return "demo"; }',
        "    @Override protected ZenithRobot createRobot() { return new org.example.teamcode.zenith.ExampleRobot(); }",
        "}",
        "",
      ].join("\n"),
    );
    expect(out.join("")).toContain("command library: Ivy (org.horizon36596.zenith.ivy)\n");
  });

  it("refuses to deploy until zenith.json names a command library, and writes nothing", () => {
    makeProject(root, {
      deploy: { kind: "directory", dir: "deploy", robotClass: "org.example.teamcode.zenith.ExampleRobot" },
    });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(() => runDeploy({ cwd: root })).toThrow(
      /does not say which command library.*"commandLibrary": "solverslib" or "commandLibrary": "ivy"/,
    );
    expect(existsSync(join(root, "deploy"))).toBe(false);
    expect(existsSync(join(root, "java"))).toBe(false);
  });

  it("needs no command library when there is no codegen section, because it then writes no Java", () => {
    makeProject(root, {
      codegen: undefined,
      deploy: { kind: "directory", dir: "deploy", robotClass: "org.example.teamcode.zenith.ExampleRobot" },
    });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(runDeploy({ cwd: root })).toBe(0);
    expect(existsSync(join(root, "deploy/demo.auto.json"))).toBe(true);
    expect(existsSync(join(root, "deploy/robot.json"))).toBe(true);
    expect(existsSync(join(root, "java"))).toBe(false);
    const text = out.join("");
    expect(text).toMatch(/^command library: none named, and none needed: zenith\.json has no "codegen" section/);
    expect(text).not.toMatch(/^(write|keep|remove): .*\.java$/m);

    out = [];
    expect(runDeploy({ cwd: root, dryRun: true, json: true })).toBe(0);
    const json = JSON.parse(out.join("")) as { commandLibrary: unknown; actions: { kind: string; path: string }[] };
    expect(json.commandLibrary).toBeNull();
    expect(json.actions.every((action) => action.kind === "copy" && !action.path.endsWith(".java"))).toBe(true);
  });

  it("says no OpMode was written when it copies autos without a codegen section, sets stubs:false and exits 0 (issue #156)", () => {
    makeProject(root, {
      codegen: undefined,
      deploy: { kind: "directory", dir: "deploy", commandLibrary: "solverslib", robotClass: "a.B" },
    });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(runDeploy({ cwd: root })).toBe(0);
    const warning =
      'no "codegen" section, so no OpMode was written; the Driver Station will not list these autos unless your own OpModes load them.';
    expect(out.join("")).toContain(warning);
    expect(existsSync(join(root, "deploy/demo.auto.json"))).toBe(true);

    out = [];
    expect(runDeploy({ cwd: root, dryRun: true, json: true })).toBe(0);
    const json = JSON.parse(out.join("")) as { stubs: unknown; commandLibrary: unknown };
    expect(json.stubs).toBe(false);
    expect(json.commandLibrary).toBe("solverslib");
  });

  it("has no OpMode warning when there are no autos to copy, or when it writes the stubs", () => {
    makeProject(root, { codegen: undefined });
    expect(runDeploy({ cwd: root, dryRun: true })).toBe(0);
    expect(out.join("")).not.toContain("no OpMode was written");

    makeProject(root);
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    out = [];
    expect(runDeploy({ cwd: root, dryRun: true })).toBe(0);
    expect(out.join("")).not.toContain("no OpMode was written");
    out = [];
    expect(runDeploy({ cwd: root, dryRun: true, json: true })).toBe(0);
    expect((JSON.parse(out.join("")) as { stubs: unknown }).stubs).toBe(true);
  });

  it("says on its first line that no Java is written when there is no codegen section, even with a library named", () => {
    makeProject(root, {
      codegen: undefined,
      deploy: { kind: "directory", dir: "deploy", commandLibrary: "ivy" },
    });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(runDeploy({ cwd: root, dryRun: true })).toBe(0);
    const first = out.join("").split("\n")[0];
    expect(first).toBe(
      'command library: Ivy is named, but none is needed: zenith.json has no "codegen" section, so no Java is written',
    );
  });

  it("names the command library in its output", () => {
    makeProject(root);
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(runDeploy({ cwd: root, dryRun: true })).toBe(0);
    expect(out.join("")).toMatch(/^command library: SolversLib \(org\.horizon36596\.zenith\.solverslib\)\n/);

    out = [];
    expect(runDeploy({ cwd: root, dryRun: true, json: true })).toBe(0);
    expect(JSON.parse(out.join("")).commandLibrary).toBe("solverslib");
  });

  it("refuses a command library it does not know", () => {
    makeProject(root, {
      deploy: { kind: "directory", dir: "deploy", commandLibrary: "ftclib", robotClass: "a.B" },
    });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(() => runDeploy({ cwd: root })).toThrow(/commandLibrary/);
  });

  it("refuses to write stubs without deploy.robotClass, and says what to set", () => {
    makeProject(root, { deploy: { kind: "directory", dir: "deploy", commandLibrary: "solverslib" } });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(() => runDeploy({ cwd: root })).toThrow(/deploy\.robotClass/);
  });

  it("exits 2 with the robotClass message when there is a codegen section and no deploy.robotClass (issue #156)", async () => {
    makeProject(root, { deploy: { kind: "directory", dir: "deploy", commandLibrary: "solverslib" } });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    const err: string[] = [];
    vi.spyOn(process.stderr, "write").mockImplementation((chunk: unknown) => {
      err.push(String(chunk));
      return true;
    });
    try {
      expect(await main(["node", "zenith", "deploy", "--project", root])).toBe(2);
    } finally {
      process.exitCode = undefined;
    }
    expect(err.join("")).toContain(
      'zenith: zenith.json has "codegen" but no "deploy.robotClass". Every OpMode zenith deploy writes constructs your robot',
    );
    expect(existsSync(join(root, "deploy"))).toBe(false);
    expect(existsSync(join(root, "java"))).toBe(false);
  });

  it("--dry-run lists the actions without writing anything", () => {
    makeProject(root);
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    const code = runDeploy({ cwd: root, dryRun: true });
    expect(code).toBe(0);
    expect(existsSync(join(root, "deploy"))).toBe(false);
    expect(out.join("")).toContain("copy:");
  });

  it("skips an auto with a finding error and reports it, but still deploys the valid ones", () => {
    makeProject(root);
    writeAuto(root, "autos", "good", simpleAuto("good"));
    writeAuto(
      root,
      "autos",
      "bad",
      simpleAuto("bad", {
        start: { pose: { xIn: -20, yIn: 0, headingRad: 0 } },
        steps: [
          {
            id: "throughWall",
            kind: "path",
            segments: [{ kind: "line", from: "current", to: { xIn: 20, yIn: 0 } }],
            heading: { mode: "tangent" },
          },
        ],
      }),
    );
    const code = runDeploy({ cwd: root });
    expect(code).toBe(1);
    expect(existsSync(join(root, "deploy/good.auto.json"))).toBe(true);
    expect(existsSync(join(root, "deploy/bad.auto.json"))).toBe(false);
  });

  it("removes a stub for an auto that no longer exists", () => {
    makeProject(root);
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    runDeploy({ cwd: root });
    const stub = join(root, "java/org/example/teamcode/opmode/Auto/generated/DemoAuto.java");
    expect(existsSync(stub)).toBe(true);

    rmSync(join(root, "autos/demo.auto.json"));
    const code = runDeploy({ cwd: root });
    expect(code).toBe(0);
    expect(existsSync(stub)).toBe(false);
  });

  it("keeps an unchanged stub rather than rewriting it", () => {
    makeProject(root);
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    runDeploy({ cwd: root });
    const stub = join(root, "java/org/example/teamcode/opmode/Auto/generated/DemoAuto.java");
    const before = readFileSync(stub, "utf8");

    out = [];
    const code = runDeploy({ cwd: root });
    expect(code).toBe(0);
    expect(readFileSync(stub, "utf8")).toBe(before);
    expect(out.join("")).toContain("keep:");
  });

  it("throws a clear error when zenith.json has no deploy section", () => {
    makeProject(root, { deploy: undefined });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(() => runDeploy({ cwd: root })).toThrow(/deploy/);
  });

  it("finding 13: refuses a deploy.dir that escapes the project root, and never creates it", () => {
    makeProject(root, { deploy: { kind: "directory", dir: "../ESCAPED" } });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(() => runDeploy({ cwd: root })).toThrow(/resolves outside the project root/);
    expect(existsSync(join(root, "..", "ESCAPED"))).toBe(false);
  });

  it("finding 13: refuses a codegen.dir that escapes the project root, and never creates it", () => {
    makeProject(root, { codegen: { package: "org.example.teamcode.opmode.Auto", dir: "../ESCAPED-CODEGEN" } });
    writeAuto(root, "autos", "demo", simpleAuto("demo"));
    expect(() => runDeploy({ cwd: root })).toThrow(/resolves outside the project root/);
    expect(existsSync(join(root, "..", "ESCAPED-CODEGEN"))).toBe(false);
  });

  it("finding 13: refuses an absolute deploy.dir outside the project root", () => {
    const outside = mkdtempSync(join(tmpdir(), "zenith-deploy-outside-"));
    try {
      makeProject(root, { deploy: { kind: "directory", dir: join(outside, "ESCAPED") } });
      writeAuto(root, "autos", "demo", simpleAuto("demo"));
      expect(() => runDeploy({ cwd: root })).toThrow(/resolves outside the project root/);
      expect(existsSync(join(outside, "ESCAPED"))).toBe(false);
    } finally {
      rmSync(outside, { recursive: true, force: true });
    }
  });
});

